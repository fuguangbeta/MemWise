def tr(s):
    """静态字符串翻译：精确匹配 → 片段全替换回退。
    片段替换处理相邻字面量拼接的字符串（如 tooltip 多行文本在运行时合并为完整串，
    映射表按行分段——精确匹配必失败，需逐片段替换）；未命中返回原文（渐进式安全）。
    仅 UI 构建等低频路径调用。门槛 len>=2（"释放 " 等 3 字符键参与）；单字键（"轮"/"秒"）走精确"""
    if _current == "zh_CN" or not s:
        return s
    hit = _EN.get(s)
    if hit is not None:
        return hit
    out = s
    replaced = False
    for k in _EN_SORTED:
        if len(k) >= 2 and k in out:
            out = out.replace(k, v := _EN[k])
            replaced = True
        elif k.endswith("\n") and len(k) >= 3 and k[:-1] in out:
            # 键带尾换行、目标串无尾换行（tooltip 末行）——去尾\n 变体匹配
            out = out.replace(k[:-1], _EN[k].rstrip("\n"))
            replaced = True
    return out if replaced else s


def _tr_msg_raw(s):
    """动态消息翻译：精确匹配 → 前缀匹配（参数后缀递归翻译）→ 片段全替换（一轮遍历全部可替键）。
    覆盖 "WS未填满(80/120)"、"🔴 守护中 90% — 内存紧张" 与多片段摘要（"释放 X · 整理 Y · 试探 Z"）三类；
    门槛 len>=2（"释放 "/"效率 "/"试探 "/"成功)" 等 3 字符键）；模板有限，微秒级——仅日志展示等低频路径"""
    if _current == "zh_CN" or not s:
        return s
    hit = _EN.get(s)
    if hit is not None:
        return hit
    for k in _EN_SORTED:
        if len(k) >= 2 and s.startswith(k) and len(s) > len(k):
            return _EN[k] + _tr_msg_raw(s[len(k):])  # 后缀递归翻译（参数保留）
    out = s
    changed = False
    for k in _EN_SORTED:
        if len(k) >= 2 and k in out:
            out = out.replace(k, _EN[k])
            changed = True
        elif k.endswith("\n") and len(k) >= 3 and k[:-1] in out:
            # 去尾 \n 变体（2026-09-06 对称补齐，与 tr 同规则）：目标串无尾换行时
            # 带尾 \n 的键也能命中（多行消息经 tr_msg 渲染的残尾消除）
            out = out.replace(k[:-1], _EN[k].rstrip("\n"))
            changed = True
    return out if changed else s


def tr_msg(s):
    """显示层消息翻译入口：翻译结果再做标点归一（2026-09-11）。
    动态拼接的消息（如候选进程名用「、」连接）源串是中文原文，顿号由逻辑层拼出来、
    不经过翻译表——英文界面下会残留中文顿号，故在显示层统一转半角逗号。"""
    out = _tr_msg_raw(s)
    if _current != "zh_CN" and "、" in out:
        out = out.replace("、", ", ")
    return out
